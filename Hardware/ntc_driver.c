//核心思路是：先用ADC读出电压，算出当前NTC的电阻值，再通过电阻值计算出温度
int measure_temp(void) {
    float ntc_v=0,ntc_r;
    int temp;
    u16 adc_value;
    //ADC输入电压Vin=(ADC外部参考参考电压*ADC值)/4096
    adc_value = Get_ADCResult(ADC_CH12);
    
    ntc_v = (adc_value*2.5)/4096;
    
    ntc_r = ntc_v* 10 / (3.3 - ntc_v);
    
    temp =  search_temp(ntc_r*100)-55;
    return  temp;
}